type TranslationKey = keyof typeof translations.en;

interface LanguageContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = localStorage.getItem("alex_portfolio_lang") as Lang;
    if (saved && (saved === "en" || saved === "uk" || saved === "ru")) {
      setLangState(saved);
    } else if (typeof navigator !== "undefined" && navigator.language) {
      const browserLang = navigator.language.split("-")[0];
      if (browserLang === "uk" || browserLang === "ru") {
        setLangState(browserLang as Lang);
      }
    }
  }, []);

  const setLang = (newLang: Lang) => {
    setLangState(newLang);
    localStorage.setItem("alex_portfolio_lang", newLang);
  };

  const t = (key: TranslationKey): string => {
    const val = (translations[lang] as Translations)[key];
    if (val === undefined) {
      const fallback = (translations["en"] as Translations)[key];
      return fallback !== undefined ? fallback : "";
    }
    return val;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used inside <LanguageProvider>");
  return ctx;
}
